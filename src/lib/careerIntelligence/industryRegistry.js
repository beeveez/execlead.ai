export function searchIndustries(query, limit = 10) {
  if (!query || !query.trim()) return INDUSTRIES.slice(0, limit);
  const q = query.toLowerCase().trim();
  return INDUSTRIES.filter(i =>
    i.name.toLowerCase().includes(q) ||
    i.description.toLowerCase().includes(q) ||
    i.recommended_competencies.some(c => c.toLowerCase().includes(q))
  ).slice(0, limit);
}

export function getIndustryById(id) {
  return INDUSTRIES.find(i => i.id === id);
}

export function getIndustryByName(name) {
  if (!name) return null;
  return INDUSTRIES.find(i => i.name.toLowerCase() === name.toLowerCase());
}